import React, { useState, useEffect } from 'react';
import { CHAPTERS, ChapterId } from '../data/chaptersData';
import { SvgAsset } from '../data/svgAssets';
import { Image, Download, Copy, Check, ShieldCheck, Layers } from 'lucide-react';

import { ChapterConfig } from '../data/chaptersData';

export interface VisualAssetGalleryProps {
  currentChapterId?: string;
  activeChapterConfig?: ChapterConfig;
  availableChapters?: ChapterConfig[];
  onChapterChange?: (id: any) => void;
}

export const VisualAssetGallery: React.FC<VisualAssetGalleryProps> = ({
  currentChapterId = 'unit1',
  activeChapterConfig,
  availableChapters = Object.values(CHAPTERS),
  onChapterChange
}) => {
  const [activeChapterId, setActiveChapterId] = useState<string>(currentChapterId);
  const chapter = activeChapterConfig || availableChapters.find(c => c.id === activeChapterId) || CHAPTERS[activeChapterId as ChapterId] || CHAPTERS.unit1;

  const firstFigKey = Object.keys(chapter.figures || {})[0] || 'fig1';
  const [selectedFigKey, setSelectedFigKey] = useState<string>(firstFigKey);
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  // Sync with prop
  useEffect(() => {
    if (currentChapterId) {
      setActiveChapterId(currentChapterId);
      const ch = activeChapterConfig || availableChapters.find(c => c.id === currentChapterId) || CHAPTERS[currentChapterId as ChapterId];
      if (ch && Object.keys(ch.figures || {}).length > 0) {
        setSelectedFigKey(Object.keys(ch.figures)[0]);
      }
    }
  }, [currentChapterId, activeChapterConfig, availableChapters]);

  const handleChapterSwitch = (id: string) => {
    setActiveChapterId(id);
    const ch = availableChapters.find(c => c.id === id) || CHAPTERS[id as ChapterId];
    if (ch && Object.keys(ch.figures || {}).length > 0) {
      setSelectedFigKey(Object.keys(ch.figures)[0]);
    }
    if (onChapterChange) {
      onChapterChange(id);
    }
  };

  const selectedFig: SvgAsset = chapter.figures[selectedFigKey] || Object.values(chapter.figures)[0];

  const downloadSvg = (asset: SvgAsset) => {
    const blob = new Blob([asset.svgContent], { type: 'image/svg+xml' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = asset.filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const copySvgMarkup = (asset: SvgAsset) => {
    navigator.clipboard.writeText(asset.svgContent);
    setCopiedKey(asset.id);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 p-4 rounded-xl bg-slate-900 border border-slate-800">
        <div>
          <div className="flex items-center gap-2">
            <Image className="w-5 h-5 text-cyan-400" />
            <h3 className="text-base font-semibold text-white">
              Vector SVG Asset Explorer
            </h3>
            <span className="text-xs px-2 py-0.5 rounded bg-cyan-950/60 text-cyan-300 border border-cyan-800/40">
              16:9 Pure White Canvas
            </span>
          </div>
          <p className="text-xs text-slate-400 mt-1">
            All vector figures generated by <code className="text-cyan-300">{chapter.pyFileName}</code> per Section 4 and Section 8 (clean white background, text size ≥ 18px, minimal hairline borders).
          </p>
        </div>

        {/* Chapter Switcher & Global actions */}
        <div className="flex items-center gap-3 flex-wrap">
          <div className="flex items-center gap-1 bg-slate-950 p-1 rounded-lg border border-slate-800 flex-wrap">
            {availableChapters.map((ch) => (
              <button
                key={ch.id}
                onClick={() => handleChapterSwitch(ch.id)}
                className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                  activeChapterId === ch.id
                    ? 'bg-cyan-600 text-white shadow-sm'
                    : 'text-slate-400 hover:text-slate-200'
                }`}
              >
                {ch.unitNumber} ({Object.keys(ch.figures || {}).length} Figs)
              </button>
            ))}
          </div>

          <button
            onClick={() => downloadSvg(selectedFig)}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 text-slate-200 hover:bg-slate-700 hover:text-white border border-slate-700 transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download {selectedFig.filename}</span>
          </button>
        </div>
      </div>

      {/* Main Grid: Selector List on Left, Active Canvas on Right */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left: Thumbnail & List Selector */}
        <div className="lg:col-span-4 space-y-2.5">
          {Object.entries(chapter.figures).map(([key, fig]) => (
            <button
              key={key}
              onClick={() => setSelectedFigKey(key)}
              className={`w-full text-left p-3.5 rounded-xl border transition-all flex flex-col gap-1.5 ${
                selectedFigKey === key
                  ? 'border-cyan-500 bg-cyan-950/20 ring-1 ring-cyan-500'
                  : 'border-slate-800 bg-slate-900/60 hover:border-slate-700 hover:bg-slate-900'
              }`}
            >
              <div className="flex items-center justify-between text-xs">
                <span className="font-mono text-cyan-400 font-semibold">{fig.filename}</span>
                <span className="text-slate-500 text-[11px]">{fig.topicRef}</span>
              </div>
              <h4 className="text-sm font-semibold text-white leading-tight">
                {fig.title}
              </h4>
              <p className="text-xs text-slate-400 line-clamp-2 leading-normal">
                {fig.description}
              </p>
            </button>
          ))}
        </div>

        {/* Right: High-Resolution 16:9 SVG Canvas */}
        <div className="lg:col-span-8 flex flex-col gap-4">
          <div className="p-4 rounded-xl bg-slate-900 border border-slate-800 flex items-center justify-between">
            <div>
              <span className="text-xs font-mono text-cyan-400 block mb-0.5">
                {selectedFig.topicRef} · {selectedFig.filename}
              </span>
              <h3 className="text-base font-bold text-white">
                {selectedFig.title}
              </h3>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={() => copySvgMarkup(selectedFig)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-800 text-slate-200 hover:bg-slate-700 border border-slate-700 transition-colors"
                title="Copy raw SVG XML code"
              >
                {copiedKey === selectedFig.id ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span className="text-emerald-400">Copied SVG</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy SVG Code</span>
                  </>
                )}
              </button>

              <button
                onClick={() => downloadSvg(selectedFig)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-cyan-600 hover:bg-cyan-500 text-white transition-colors"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Save SVG</span>
              </button>
            </div>
          </div>

          {/* 16:9 Vector Canvas Stage (Clean white background, minimal borders) */}
          <div className="w-full aspect-[16/9] bg-white rounded-xl border border-slate-200/50 p-2 sm:p-4 overflow-hidden shadow-2xl flex items-center justify-center">
            <div
              className="w-full h-full flex items-center justify-center rounded-lg overflow-hidden [&>svg]:w-full [&>svg]:h-full [&>svg]:object-contain"
              dangerouslySetInnerHTML={{ __html: selectedFig.svgContent }}
            />
          </div>

          {/* Master Prompt Specifications Audit Card */}
          <div className="p-4 rounded-xl bg-slate-900/90 border border-slate-800 grid grid-cols-1 sm:grid-cols-3 gap-3 text-xs">
            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-400 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-200 block">White Canvas &amp; Clear Contrast</span>
                <span className="text-slate-400 text-[11px]">100% white (#ffffff) canvas with high-contrast text and minimal borders.</span>
              </div>
            </div>

            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-400 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-200 block">Minimum 18px+ Font Floor</span>
                <span className="text-slate-400 text-[11px]">Every diagram label and annotation is scaled ≥ 18px for projection clarity.</span>
              </div>
            </div>

            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-400 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-200 block">16:9 Vector Fidelity</span>
                <span className="text-slate-400 text-[11px]">viewBox 1600x900 ensures zero pixelation on 4K university screens.</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
