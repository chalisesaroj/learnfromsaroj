import React, { useState, useEffect } from 'react';
import { CHAPTERS, ChapterId } from '../data/chaptersData';
import { SvgAsset } from '../data/svgAssets';
import { Image, Download, Copy, Check, ShieldCheck, Maximize2, X } from 'lucide-react';

import { ChapterConfig } from '../data/chaptersData';

export interface VisualAssetGalleryProps {
  currentChapterId?: string;
  activeChapterConfig?: ChapterConfig;
  availableChapters?: ChapterConfig[];
  onChapterChange?: (id: any) => void;
}

export const VisualAssetGallery: React.FC<VisualAssetGalleryProps> = ({
  currentChapterId = 'unit1',
  activeChapterConfig,
  availableChapters = Object.values(CHAPTERS),
  onChapterChange
}) => {
  const [activeChapterId, setActiveChapterId] = useState<string>(currentChapterId);
  const chapter = activeChapterConfig || availableChapters.find(c => c.id === activeChapterId) || CHAPTERS[activeChapterId as ChapterId] || CHAPTERS.unit1;

  const firstFigKey = Object.keys(chapter.figures || {})[0] || 'fig1';
  const [selectedFigKey, setSelectedFigKey] = useState<string>(firstFigKey);
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [isZoomOpen, setIsZoomOpen] = useState<boolean>(false);

  // Sync with prop
  useEffect(() => {
    if (currentChapterId) {
      setActiveChapterId(currentChapterId);
      const ch = activeChapterConfig || availableChapters.find(c => c.id === currentChapterId) || CHAPTERS[currentChapterId as ChapterId];
      if (ch && Object.keys(ch.figures || {}).length > 0) {
        setSelectedFigKey(Object.keys(ch.figures)[0]);
      }
    }
  }, [currentChapterId, activeChapterConfig, availableChapters]);

  const handleChapterSwitch = (id: string) => {
    setActiveChapterId(id);
    const ch = availableChapters.find(c => c.id === id) || CHAPTERS[id as ChapterId];
    if (ch && Object.keys(ch.figures || {}).length > 0) {
      setSelectedFigKey(Object.keys(ch.figures)[0]);
    }
    if (onChapterChange) {
      onChapterChange(id);
    }
  };

  const selectedFig: SvgAsset = chapter.figures[selectedFigKey] || Object.values(chapter.figures)[0];

  const downloadSvg = (asset: SvgAsset) => {
    const blob = new Blob([asset.svgContent], { type: 'image/svg+xml' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = asset.filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const copySvgMarkup = (asset: SvgAsset) => {
    navigator.clipboard.writeText(asset.svgContent);
    setCopiedKey(asset.id);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 p-4 rounded-xl bg-white border border-slate-200 shadow-xs">
        <div>
          <div className="flex items-center gap-2 flex-wrap">
            <Image className="w-5 h-5 text-cyan-600" />
            <h3 className="text-base font-semibold text-slate-900">
              Vector SVG Asset Explorer
            </h3>
            <span className="text-xs text-cyan-700 font-mono">
              · 16:9 Pure White Canvas
            </span>
          </div>
          <p className="text-sm text-slate-600 mt-1">
            All vector figures generated by <code className="text-cyan-700 font-semibold">{chapter.pyFileName}</code> (clean white background, Times New Roman typography, minimum 20px+ diagram text, high-contrast labels).
          </p>
        </div>

        {/* Chapter Switcher & Global actions */}
        <div className="flex items-center gap-3 flex-wrap">
          <div className="flex items-center gap-1 bg-slate-100 p-1 rounded-lg border border-slate-200 flex-wrap">
            {availableChapters.map((ch) => (
              <button
                key={ch.id}
                onClick={() => handleChapterSwitch(ch.id)}
                className={`px-3 py-1.5 rounded text-xs font-semibold transition-all ${
                  activeChapterId === ch.id
                    ? 'bg-cyan-600 text-white shadow-xs'
                    : 'text-slate-600 hover:text-slate-900 hover:bg-white'
                }`}
              >
                {ch.unitNumber} ({Object.keys(ch.figures || {}).length} Figs)
              </button>
            ))}
          </div>

          <button
            onClick={() => downloadSvg(selectedFig)}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-white text-slate-700 hover:bg-slate-100 hover:text-slate-900 border border-slate-300 transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download {selectedFig.filename}</span>
          </button>
        </div>
      </div>

      {/* Main Grid: Selector List on Left, Active Canvas on Right */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left: Thumbnail & List Selector */}
        <div className="lg:col-span-4 space-y-2.5">
          {Object.entries(chapter.figures).map(([key, fig]) => (
            <button
              key={key}
              onClick={() => setSelectedFigKey(key)}
              className={`w-full text-left p-3.5 rounded-xl border transition-all flex flex-col gap-1.5 ${
                selectedFigKey === key
                  ? 'border-cyan-500 bg-cyan-50/70 ring-1 ring-cyan-500/40 shadow-xs'
                  : 'border-slate-200 bg-white hover:border-slate-300 hover:bg-slate-50'
              }`}
            >
              <div className="flex items-center justify-between text-xs">
                <span className="font-mono text-cyan-700 font-semibold">{fig.filename}</span>
                <span className="text-slate-500 text-[11px]">{fig.topicRef}</span>
              </div>
              <h4 className="text-sm font-semibold text-slate-900 leading-tight">
                {fig.title}
              </h4>
              <p className="text-xs text-slate-600 line-clamp-2 leading-normal">
                {fig.description}
              </p>
            </button>
          ))}
        </div>

        {/* Right: High-Resolution 16:9 SVG Canvas */}
        <div className="lg:col-span-8 flex flex-col gap-4">
          <div className="p-4 rounded-xl bg-white border border-slate-200 shadow-xs flex items-center justify-between gap-3 flex-wrap">
            <div>
              <span className="text-xs font-mono text-cyan-700 block mb-0.5 font-medium">
                {selectedFig.topicRef} · {selectedFig.filename}
              </span>
              <h3 className="text-base font-bold text-slate-900">
                {selectedFig.title}
              </h3>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={() => copySvgMarkup(selectedFig)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-100 text-slate-700 hover:bg-slate-200 border border-slate-200 transition-colors"
                title="Copy raw SVG XML code"
              >
                {copiedKey === selectedFig.id ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span className="text-emerald-700">Copied SVG</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy SVG Code</span>
                  </>
                )}
              </button>

              <button
                onClick={() => setIsZoomOpen(true)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-slate-900 hover:bg-slate-800 text-white transition-colors"
                title="Open full-screen vector view"
              >
                <Maximize2 className="w-3.5 h-3.5" />
                <span>Full View</span>
              </button>

              <button
                onClick={() => downloadSvg(selectedFig)}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium bg-cyan-600 hover:bg-cyan-700 text-white transition-colors"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Save SVG</span>
              </button>
            </div>
          </div>

          {/* 16:9 Vector Canvas Stage */}
          <div
            onClick={() => setIsZoomOpen(true)}
            className="w-full aspect-[16/9] bg-white rounded-xl border border-slate-200 p-1 overflow-hidden shadow-md flex items-center justify-center relative group cursor-zoom-in"
            title="Click to enlarge diagram"
          >
            <div
              className="w-full h-full flex items-center justify-center rounded-lg overflow-hidden [&>svg]:w-full [&>svg]:h-full [&>svg]:object-contain"
              dangerouslySetInnerHTML={{ __html: selectedFig.svgContent }}
            />
            <div className="absolute bottom-3 right-3 px-2.5 py-1 rounded-md bg-slate-900/75 text-white text-xs font-semibold flex items-center gap-1.5 opacity-0 group-hover:opacity-100 transition-opacity pointer-events-none">
              <Maximize2 className="w-3.5 h-3.5" />
              <span>Click to Enlarge</span>
            </div>
          </div>

          {/* Master Prompt Specifications Audit Card */}
          <div className="p-4 rounded-xl bg-white border border-slate-200 grid grid-cols-1 sm:grid-cols-3 gap-3 text-xs shadow-xs">
            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-600 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-900 block">White Canvas &amp; Clear Contrast</span>
                <span className="text-slate-600 text-xs">100% white (#ffffff) canvas with high-contrast text and minimal borders.</span>
              </div>
            </div>

            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-600 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-900 block">Minimum 20px+ Font Floor</span>
                <span className="text-slate-600 text-xs">Every diagram label and annotation is scaled ≥ 20px for projection clarity.</span>
              </div>
            </div>

            <div className="flex items-start gap-2.5">
              <ShieldCheck className="w-4 h-4 text-emerald-600 mt-0.5 shrink-0" />
              <div>
                <span className="font-semibold text-slate-900 block">16:9 Vector Fidelity</span>
                <span className="text-slate-600 text-xs">viewBox 1600x900 ensures zero pixelation on 4K university screens.</span>
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Fullscreen SVG Lightbox Modal */}
      {isZoomOpen && (
        <div
          onClick={() => setIsZoomOpen(false)}
          className="fixed inset-0 z-50 bg-slate-900/80 backdrop-blur-sm flex items-center justify-center p-4 sm:p-6 cursor-zoom-out"
        >
          <div
            onClick={(e) => e.stopPropagation()}
            className="w-full max-w-[94vw] max-h-[92vh] bg-white rounded-2xl border border-slate-200 shadow-2xl p-4 sm:p-5 flex flex-col gap-3 cursor-default"
          >
            <div className="flex items-center justify-between gap-3 border-b border-slate-200 pb-2.5">
              <h4 className="font-bold text-slate-900 text-base sm:text-lg truncate">
                {selectedFig.title}
              </h4>
              <div className="flex items-center gap-2 shrink-0">
                <button
                  onClick={() => downloadSvg(selectedFig)}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-cyan-600 hover:bg-cyan-700 text-white transition-colors"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>Save SVG</span>
                </button>
                <button
                  onClick={() => setIsZoomOpen(false)}
                  className="p-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 transition-colors"
                  aria-label="Close enlarged diagram"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div
              className="w-full aspect-[16/9] max-h-[80vh] flex items-center justify-center bg-white rounded-xl overflow-hidden [&>svg]:w-full [&>svg]:h-full [&>svg]:object-contain"
              dangerouslySetInnerHTML={{ __html: selectedFig.svgContent }}
            />
          </div>
        </div>
      )}
    </div>
  );
};
